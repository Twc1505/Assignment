    private void saveBookedDataToFile(){
        File file = new File("slots.txt");
        List<String> allSlots = new ArrayList<>();

        // Step 1: Load all slots from the file
        if (file.exists()) {
            try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
                String line;
                while ((line = reader.readLine()) != null) {
                    allSlots.add(line);
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error reading slots file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        // Step 2: Update the relevant slot
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            String slotID = (String) model.getValueAt(i, 0); // Slot ID
            String updatedSlot = ""; // Construct the updated slot line

            for (int j = 0; j < model.getColumnCount(); j++) {
                updatedSlot += model.getValueAt(i, j);
                if (j < model.getColumnCount() - 1) {
                    updatedSlot += ","; // Add comma between values
                }
            }

            // Replace the corresponding slot in allSlots
            for (int k = 0; k < allSlots.size(); k++) {
                if (allSlots.get(k).startsWith(slotID + ",")) {
                    allSlots.set(k, updatedSlot); // Update the line for the specific slot
                    break;
                }
            }
        }

        // Step 3: Save all slots back to the file
        try (PrintWriter writer = new PrintWriter(new FileWriter(file))) {
            for (String slot : allSlots) {
                writer.println(slot);
            }
            JOptionPane.showMessageDialog(this, "Consultation slot booked successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving slots: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
}
    private void saveDataToAppointmentFile(int selectedRow, String bookingDate) {
        // Check if the appointment file exists, create it if not
        File appointmentFile = new File("appointment.txt");
        if (!appointmentFile.exists()) {
            try {
                appointmentFile.createNewFile();  // Create the file if it doesn't exist
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error creating appointment file: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                return; // Exit method if file creation fails
            }
        }
        
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();

        // Retrieve data from the selected row
        String slotsID = (String) model.getValueAt(selectedRow, 0); // Slot ID
        String lecturerID = (String) model.getValueAt(selectedRow, 1); // Lecturer ID
        String lecturerName = (String) model.getValueAt(selectedRow, 2); // Lecturer Name
        String timeSlots = (String) model.getValueAt(selectedRow, 3); // Time Slot

        // Create User objects for student and lecturer
        User student = user; // Current logged-in user
        User lecturer = new User(lecturerID, lecturerName, null, null, null); // Lecturer

        // Create Consultation object
        Consultation consultation = new Consultation(slotsID, null,timeSlots);

        // Generate a unique Appointment ID and timestamp
        String appointmentID = "A" + (System.currentTimeMillis() / 1000);
        LocalDateTime bookingTimestamp = LocalDateTime.now();
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm:ss");
        String formattedTimestamp = bookingTimestamp.format(formatter);

        // Create an Appointment object
        Appointment appointment = new Appointment(
            appointmentID, 
            student, 
            lecturer, 
            consultation, 
            bookingDate, 
            bookingTimestamp, 
            "Pending", 
            "Pending", 
            "None", 
            "None",
            "None", 
            "None"
        );

        // Save appointment details into the file
        try (java.io.PrintWriter writer = new java.io.PrintWriter(new java.io.FileWriter("appointment.txt", true))) {
            writer.println(String.join(",", appointment.toArray())); // Write appointment data
            JOptionPane.showMessageDialog(this, "Appointment saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving appointment: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
}

    private void loadDataFromFile() {
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        String[] colHeadings = {"SlotsID", "LectureID", "Name", "TimeSlots"};
        model.setColumnIdentifiers(colHeadings); // Set column headers

        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader("slots.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] row = line.split(","); // Split each line by commas
                // Filter by StudentID
                //if (row[1].equals(userid)) {
                    //model.addRow(row); // Add only rows that match the logged-in lecturer
                //}
                if (row.length == colHeadings.length) {
                    model.addRow(row);
                }
            }
        } catch (IOException e) {
            // Handle case where file doesn't exist or other I/O errors
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Error loading data: " + e.getMessage(), 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
