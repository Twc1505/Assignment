    // Method to check if a slot is already booked
    private boolean isSlotBooked(String slotID, String date, String timeSlot) {
        try (BufferedReader br = new BufferedReader(new FileReader("appointment.txt"))) {
            String line;
            DateTimeFormatter dateTimeFormatter = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm:ss"); // Updated format
            while ((line = br.readLine()) != null) {
                String[] row = line.split(",");
                try {
                    LocalDateTime bookingTimestamp = LocalDateTime.parse(row[8], dateTimeFormatter);
                    Appointment appointment = new Appointment(
                        row[0], // appointmentID
                        new User(row[1], row[2], null, null, null), // student
                        new User(row[4], row[5], null, null, null), // lecturer
                        new Consultation(row[3], null, row[6]), // consultation
                        row[7], // bookingDate
                        bookingTimestamp, // bookingTimestamp
                        row[9], // status
                        row[10], // notes
                        row[11], // studentFeedback
                        row[12], // studentRating
                        row[13], // lecturerFeedback
                        row[14] // lecturerRating
                    );

                    // Check if the slot is booked
                    if (appointment.getConsultation().getSlotID().equals(slotID) &&
                        appointment.getBookingDate().equals(date) &&
                        appointment.getConsultation().getTimeSlot().equals(timeSlot) &&
                        !appointment.getStatus().equalsIgnoreCase("Rejected")) {
                        return true; // Slot is already booked
                    }
                } catch (DateTimeParseException e) {
                    JOptionPane.showMessageDialog(this, "Error parsing date-time: " + row[8], "Error", JOptionPane.ERROR_MESSAGE);
                    continue; // Skip this entry
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error checking slot availability: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        return false; // Slot is available
    }
    private void BookConsultationBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BookConsultationBtnActionPerformed
         int selectedRow = jTable3.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a row to book the consultation", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Retrieve slot details from the selected row
    String slotID = (String) jTable3.getValueAt(selectedRow, 0);
    String inputDate = Datetextfield.getText().trim();
    String selectedTimeSlot = (String) jTable3.getValueAt(selectedRow, 3);
    
    // Validate the booking date
    DateTimeFormatter dateFormatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
    DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("h:mma");
    LocalDate parsedDate;

    try {
        // Parse the input date
        parsedDate = LocalDate.parse(inputDate, dateFormatter);

        // Check if the selected date is in the past
        if (parsedDate.isBefore(LocalDate.now())) {
            JOptionPane.showMessageDialog(this, "The selected date is in the past. Please choose a future date.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // If the booking is for today, validate the time slot
        if (parsedDate.isEqual(LocalDate.now())) {
            // Assume the time slot is provided separately
            String endTimeString = selectedTimeSlot; // Example; replace with actual input
            LocalTime endTime = LocalTime.parse(endTimeString, timeFormatter);

            // Compare the end time with the current time
            if (LocalTime.now().isAfter(endTime)) {
                JOptionPane.showMessageDialog(this, "This time slot has already passed. Please select a valid time.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
    } catch (DateTimeParseException e) {
        JOptionPane.showMessageDialog(this, "Invalid date format! Please use dd/MM/yyyy.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }



    // Check if the slot is already booked
    if (isSlotBooked(slotID, inputDate, selectedTimeSlot)) {
        JOptionPane.showMessageDialog(this, "This slot is already booked by another student. Please choose a different slot.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Confirm the booking
    int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to book this slot for " + inputDate + "?", "Confirm Booking", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        saveBookedDataToFile(); // Save updated data back to the file
        saveDataToAppointmentFile(selectedRow, inputDate); // Save appointment details
    }
    }//GEN-LAST:event_BookConsultationBtnActionPerformed

