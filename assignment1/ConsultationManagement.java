    private void loadDataFromFile() {
        DefaultTableModel model = (DefaultTableModel) jTable.getModel();
        String[] colHeadings = {"SlotsID", "LectureID", "Name", "TimeSlots"};
        model.setColumnIdentifiers(colHeadings); // Update column headers

        try (BufferedReader br = new BufferedReader(new FileReader("slots.txt"))) {
            String line;
            boolean fileHasData = false; // To check if the file already has data

            while ((line = br.readLine()) != null) {
                fileHasData = true;
                String[] row = line.split(",");

                // Ensure the row is valid (has at least 4 elements) and check if the UserID matches
                if (row.length >= 4) {
                    String slotID = row[0];
                    String userID = row[1]; // Assuming userID is in the 2nd position
                    String name = row[2];
                    String timeSlot = row[3];

                    // Check if the current row belongs to the logged-in user
                    if (userID.equals(user.getUserID())) {
                        // Add consultation to the list and table for this user
                        Consultation consultation = new Consultation(slotID, user, timeSlot);
                        consultations.add(consultation);
                        model.addRow(consultation.toArray()); // Add consultation to table
                    }
                }
            }

            // If no consultations were loaded from the file, load default time slots
            if (!fileHasData || consultations.isEmpty()) {
                loadDefaultTimeSlots();
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, 
                "File not found or error reading file. Default slots will be loaded.", 
                "Notice", 
                JOptionPane.INFORMATION_MESSAGE);
            loadDefaultTimeSlots(); // Fallback to default slots if file read fails
        }
    }

    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        DefaultTableModel model = (DefaultTableModel) jTable.getModel();
        int selectedRow = jTable.getSelectedRow();

        // Check if a row is selected
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to delete.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Confirm deletion
        int response = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete the selected row?", 
            "Confirm Delete", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.QUESTION_MESSAGE);

        if (response == JOptionPane.YES_OPTION) {
            try {
                // Get the consultation data from the selected row
                String lectureID = (String) model.getValueAt(selectedRow, 1); // Column 1: Lecture ID
                String timeSlot = (String) model.getValueAt(selectedRow, 3);  // Column 3: Time Slot
                String userID = user.getUserID();  // Get the user ID

                // Find and remove the consultation for the current user
                Consultation selectedConsultation = consultations.get(selectedRow);
                if (selectedConsultation.getLectureID().equals(userID)) {
                    consultations.remove(selectedRow);
                    model.removeRow(selectedRow);

                    // Rewrite the slots file to exclude the deleted consultation
                    consultationFile();  // This method ensures only the current user's data is updated

                    JOptionPane.showMessageDialog(this, "Consultation deleted successfully.", 
                        "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "You cannot delete a consultation that doesn't belong to you.", 
                        "Error", JOptionPane.ERROR_MESSAGE);
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, 
                    "Error deleting consultation: " + e.getMessage(), 
                    "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_DeleteBtnActionPerformed

