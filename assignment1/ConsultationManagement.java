    private void ModifyBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ModifyBtnActionPerformed
        DefaultTableModel model = (DefaultTableModel) jTable.getModel();
    int selectedRow = jTable.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a row to modify.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Get the selected consultation's user ID and check if it belongs to the current user
    String lectureID = (String) model.getValueAt(selectedRow, 1);  // Column 1: Lecture ID
    String currentUserID = user.getUserID();  // Get the current user ID

    if (!lectureID.equals(currentUserID)) {
        javax.swing.JOptionPane.showMessageDialog(this, "You can only modify your own consultations.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Populate the input fields with the selected row's data
    String timeSlot = model.getValueAt(selectedRow, 3).toString();  // Column 3: Time Slot
    TimeSlots.setText(timeSlot);
    }//GEN-LAST:event_ModifyBtnActionPerformed

    private void SaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveBtnActionPerformed
        String timeSlot = TimeSlots.getText().trim();

        if (timeSlot.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String uniqueSlotID = generateUniqueSlotID();  // Generate unique slot ID
        Consultation newConsultation = new Consultation(uniqueSlotID, user, timeSlot);  // Create a new consultation

        // Add the new consultation to the list
        consultations.add(newConsultation);

        // Update the table with the new consultation
        DefaultTableModel model = (DefaultTableModel) jTable.getModel();
        model.addRow(newConsultation.toArray());

        // Clear input fields
        TimeSlots.setText("");

        // Save the updated consultations to the file (only for the current user)
        consultationFile();  // This method writes the current user's consultations to the file

        // Show success message
        javax.swing.JOptionPane.showMessageDialog(this, "Record added successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_SaveBtnActionPerformed

